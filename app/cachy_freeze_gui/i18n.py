def configure(language: str) -> str:
    global _language
    _language = language if language in {"en", "tr"} else "en"
    return _language


def current_language() -> str:
    return _language


def preferred_language() -> str:
    path = Path("/var/lib/cachy-freeze/settings.json")
    try:
        value = json.loads(path.read_text(encoding="utf-8")).get("language")
        if value in {"en", "tr"}:
            return str(value)
    except (OSError, AttributeError, json.JSONDecodeError):
        pass
    system_locale = locale.getlocale()[0] or ""
    return "tr" if system_locale.casefold().startswith("tr") else "en"


def tr(value: str) -> str:
    if _language != "tr" or not value:
        return value
    if value in TR:
        return TR[value]
    result = value
    for source in sorted(TR, key=len, reverse=True):
        if len(source) >= 4 and source in result:
            result = result.replace(source, TR[source])
    return result
